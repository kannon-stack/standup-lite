function ConvertTo-WslPath([string]$WindowsPath) {
    $p = $WindowsPath -replace '\\', '/'
    if ($p -match '^([A-Za-z]):(.*)$') {
        return "/mnt/$($Matches[1].ToLower())$($Matches[2])"
    }
    return $p
}

function Invoke-PveWsl {
    param(
        [string]$Command,
        [string]$User = "root",
        [switch]$IgnoreExit
    )
    $output = & wsl.exe -d $WslDistro -u $User -- bash -lc $Command 2>&1
    $code = $LASTEXITCODE
    if ($output) { $output | ForEach-Object { Write-Host $_ } }
    if (-not $IgnoreExit -and $code -ne 0) {
        throw "WSL command failed (exit $code): $Command"
    }
    return $code
}

